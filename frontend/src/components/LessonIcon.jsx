/**
 * Topic-accurate Lesson Icon component for LevelUp
 */
export function LessonIcon({
  lesson,
  course,
  size = 20,
  strokeWidth = 2,
  className = "",
  ...props
}) {
  const iconName = getLessonIconName(lesson, course);
  const IconComponent = ICON_REGISTRY[iconName] || BookOpen;

  return (
    <IconComponent
      size={size}
      strokeWidth={strokeWidth}
      className={`lesson-icon-svg ${className}`.trim()}
      aria-hidden="true"
      {...props}
    />
  );
}

export default LessonIcon;
